export type Key = keyof typeof en;

export function useI18n() {
    const locale = (usePage().props.locale as string | undefined) ?? 'pt-BR';
    const dict = dictionaries[locale] ?? ptBR;
    setLocale(locale);
    return {
        locale,
        t: (key: Key, vars: Record<string, string | number> = {}): string => interpolate(dict[key] ?? ptBR[key], vars, locale),
    };
}
